def sanitize_user_input(text: str, max_len: int = 8000) -> str:
    """三引号定界配合的清洗：转义边界、剔除零宽字符、截断超长输入。"""
    s = str(text)
    s = s.replace('"""', r"\"\"\"")
    s = s.replace("\u200b", "").replace("\u200c", "").replace("\u200d", "")
    return s[:max_len]


